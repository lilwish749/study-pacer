-- ============================================================
-- Study Pacer · Supabase 初始化脚本
-- 在 Supabase Dashboard → SQL Editor 中整段粘贴执行（只需执行一次）
-- 前提：Authentication → Providers → Email 已启用，并关闭 Confirm email
-- ============================================================

-- 1) 用户资料表
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

-- 用户名不区分大小写唯一
create unique index if not exists profiles_username_lower_key
  on public.profiles (lower(username));

-- 2) 登录日志表
create table if not exists public.login_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  username text not null,
  login_at timestamptz not null default now(),
  user_agent text
);

create index if not exists login_logs_login_at_idx
  on public.login_logs (login_at desc);

-- ============================================================
-- 3) RLS：profiles
-- ============================================================
alter table public.profiles enable row level security;

drop policy if exists "profiles readable by authenticated" on public.profiles;
create policy "profiles readable by authenticated"
  on public.profiles for select
  to authenticated
  using (true);

drop policy if exists "profiles insert self" on public.profiles;
create policy "profiles insert self"
  on public.profiles for insert
  to authenticated
  with check (auth.uid() = id);

drop policy if exists "profiles update self" on public.profiles;
create policy "profiles update self"
  on public.profiles for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- 双重保险：登录用户不能直接改 is_admin 列
revoke update on public.profiles from authenticated;
grant update (username) on public.profiles to authenticated;

create or replace function public.protect_is_admin()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- 有登录身份（非 service_role）时禁止改动 is_admin；
  -- 在 SQL Editor / 后台直接更新时 auth.uid() 为空，不会被拦截。
  if new.is_admin is distinct from old.is_admin
     and auth.uid() is not null
     and coalesce(auth.role(), '') <> 'service_role' then
    raise exception '只有管理员或后台服务可以修改 is_admin';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_protect_is_admin on public.profiles;
create trigger trg_protect_is_admin
  before update on public.profiles
  for each row execute function public.protect_is_admin();

-- 注册插入时强制 is_admin = false，防止前端伪造管理员
create or replace function public.force_profile_defaults()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null and coalesce(auth.role(), '') <> 'service_role' then
    new.is_admin := false;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_force_profile_defaults on public.profiles;
create trigger trg_force_profile_defaults
  before insert on public.profiles
  for each row execute function public.force_profile_defaults();

-- ============================================================
-- 4) RLS：login_logs
-- ============================================================
alter table public.login_logs enable row level security;

-- 只能写入自己的记录
drop policy if exists "login_logs insert own" on public.login_logs;
create policy "login_logs insert own"
  on public.login_logs for insert
  to authenticated
  with check (auth.uid() = user_id);

-- 只有管理员能读全部记录（普通用户连自己的一条也读不到）
drop policy if exists "login_logs admin read" on public.login_logs;
create policy "login_logs admin read"
  on public.login_logs for select
  to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.is_admin = true
    )
  );

-- 写入时用 profiles 里的用户名覆盖前端传入值，防止伪造
create or replace function public.force_log_username()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select p.username into new.username
  from public.profiles p
  where p.id = new.user_id;

  if new.username is null then
    raise exception '找不到用户资料，无法写入登录日志';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_force_log_username on public.login_logs;
create trigger trg_force_log_username
  before insert on public.login_logs
  for each row execute function public.force_log_username();

-- ============================================================
-- 5) 用户学习数据（跨设备同步）
-- 每个账号一行，整份应用状态存放在 data 里，登录后自动拉取/回写。
-- ============================================================
create table if not exists public.user_states (
  user_id uuid primary key references auth.users (id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.user_states enable row level security;

drop policy if exists "user_states read own" on public.user_states;
create policy "user_states read own"
  on public.user_states for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "user_states insert own" on public.user_states;
create policy "user_states insert own"
  on public.user_states for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "user_states update own" on public.user_states;
create policy "user_states update own"
  on public.user_states for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant select, insert, update on public.user_states to authenticated;

